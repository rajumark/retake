/**
 * Writes files as base64 chunks into a Kotlin object, `files: Map<name, Array<String>>`.
 * Used for the model on targets without jar resources, and for the test vectors in commonTest.
 */
abstract class EmbedFilesTask : DefaultTask() {
    @get:InputFiles @get:PathSensitive(PathSensitivity.NAME_ONLY) abstract val sources: ConfigurableFileCollection
    @get:Input abstract val objectName: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val chunk = 60_000 // multiple of 4, well under the 64K string-literal limits
        val out = StringBuilder()
        out.append("// GENERATED by the ${name} task from ${sources.files.joinToString { it.name }}. Do not edit.\n")
        out.append("package io.github.rajumark.hoverfly.retake.internal\n\n")
        out.append("internal object ${objectName.get()} {\n")
        out.append("    val files: Map<String, Array<String>> by lazy {\n        mapOf(\n")
        for (f in sources.files.sortedBy { it.name }) {
            val b64 = Base64.getEncoder().encodeToString(f.readBytes())
            out.append("            \"${f.name}\" to arrayOf(\n")
            for (i in b64.indices step chunk) out.append("                \"").append(b64, i, minOf(b64.length, i + chunk)).append("\",\n")
            out.append("            ),\n")
        }
        out.append("        )\n    }\n}\n")
        val dir = outputDir.get().asFile.resolve("io/github/rajumark/hoverfly/retake/internal")
        dir.deleteRecursively(); dir.mkdirs()
        dir.resolve("${objectName.get()}.kt").writeText(out.toString())
    }
}

val modelDir = layout.projectDirectory.dir("src/modelData")
val embedModel = tasks.register<EmbedFilesTask>("generateEmbeddedModel") {
    sources.from(modelDir.dir("io/github/rajumark/hoverfly/retake/model").asFileTree)
    objectName = "EmbeddedModel"
    outputDir = layout.buildDirectory.dir("generated/embeddedModel/kotlin")
}
val embedTestVectors = tasks.register<EmbedFilesTask>("generateTestVectors") {
    sources.from(layout.projectDirectory.file("src/commonTest/testData/testvectors.bin"))
    objectName = "TestData"
    outputDir = layout.buildDirectory.dir("generated/testData/kotlin")
}

